export function textMask(text: string, glyphs: Record<string, Grid>, spacing = 1): Mask {
  const gs = [...text].map(ch => {
    const g = glyphs[ch]
    if (!g) throw new Error(`no glyph for '${ch}'`)
    return g
  })
  const h = Math.max(...gs.map(g => g.length))
  const w = gs.reduce((sum, g) => sum + g[0].length, 0) + spacing * (gs.length - 1)
  const m: Mask = { w, h, on: new Uint8Array(w * h) }
  let x0 = 0
  for (const g of gs) {
    g.forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== '.') m.on[y * w + x0 + x] = 1 }))
    x0 += g[0].length + spacing
  }
  return m
}
